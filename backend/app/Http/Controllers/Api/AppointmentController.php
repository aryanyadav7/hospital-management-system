<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Appointment;
use App\Models\Doctor;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\Rule;
use Illuminate\Validation\ValidationException;

class AppointmentController extends Controller
{
    private const STATUSES = [
        'scheduled',
        'confirmed',
        'completed',
        'cancelled',
        'no_show',
    ];

    public function index(Request $request): JsonResponse
    {
        $query = Appointment::with([
            'patient',
            'doctor',
            'department',
        ]);

        if ($request->filled('search')) {
            $search = $request->input('search');

            $query->where(function ($q) use ($search) {
                $q->where('appointment_number', 'like', "%{$search}%")
                    ->orWhere('reason', 'like', "%{$search}%")
                    ->orWhereHas('patient', function ($patientQuery) use ($search) {
                        $patientQuery->where('name', 'like', "%{$search}%")
                            ->orWhere('patient_id', 'like', "%{$search}%");
                    })
                    ->orWhereHas('doctor', function ($doctorQuery) use ($search) {
                        $doctorQuery->where('name', 'like', "%{$search}%");
                    });
            });
        }

        foreach (['doctor_id', 'department_id', 'patient_id'] as $filter) {
            if ($request->filled($filter)) {
                $query->where($filter, $request->input($filter));
            }
        }

        if ($request->filled('status')) {
            $query->where('status', $request->input('status'));
        }

        if ($request->filled('date')) {
            $query->whereDate('appointment_date', $request->input('date'));
        }

        if ($request->filled('from_date')) {
            $query->whereDate(
                'appointment_date',
                '>=',
                $request->input('from_date')
            );
        }

        if ($request->filled('to_date')) {
            $query->whereDate(
                'appointment_date',
                '<=',
                $request->input('to_date')
            );
        }

        $perPage = min(
            max((int) $request->input('per_page', 5), 1),
            100
        );

        $appointments = $query
            ->orderByDesc('appointment_date')
            ->orderByDesc('appointment_time')
            ->paginate($perPage);

        return response()->json([
            'success' => true,
            'data' => $appointments,
        ]);
    }

    public function today(Request $request): JsonResponse
    {
        $perPage = min(
            max((int) $request->input('per_page', 10), 1),
            100
        );

        $appointments = Appointment::with([
            'patient',
            'doctor',
            'department',
        ])
            ->whereDate('appointment_date', today())
            ->orderBy('appointment_time')
            ->paginate($perPage);

        return response()->json([
            'success' => true,
            'data' => $appointments,
        ]);
    }

    public function store(Request $request): JsonResponse
    {
        $validated = $this->validateAppointment($request);

        // Appointment numbers are generated by the model.
        unset($validated['appointment_number']);

        $this->ensureDoctorDepartment(
            $validated['doctor_id'],
            $validated['department_id']
        );

        $this->ensureSlotAvailable(
            $validated['doctor_id'],
            $validated['appointment_date'],
            $validated['appointment_time']
        );

        $appointment = DB::transaction(function () use ($validated) {
            return Appointment::create([
                ...$validated,
                'status' => $validated['status'] ?? 'scheduled',
            ]);
        });

        return response()->json([
            'success' => true,
            'message' => 'Appointment created successfully.',
            'data' => $appointment->fresh([
                'patient',
                'doctor',
                'department',
            ]),
        ], 201);
    }

    public function show(Appointment $appointment): JsonResponse
    {
        return response()->json([
            'success' => true,
            'data' => $appointment->load([
                'patient',
                'doctor',
                'department',
            ]),
        ]);
    }

    public function update(
        Request $request,
        Appointment $appointment
    ): JsonResponse {
        $isPatch = $request->isMethod('patch');

        $validated = $this->validateAppointment(
            $request,
            $isPatch
        );

        unset($validated['appointment_number']);

        if (empty($validated)) {
            throw ValidationException::withMessages([
                'request' => [
                    'Please provide at least one field to update.',
                ],
            ]);
        }

        // Combine existing values with supplied PATCH values.
        // This ensures the booking rules are checked against the
        // complete appointment, not only the fields being changed.
        $effectiveValues = array_merge([
            'patient_id' => $appointment->patient_id,
            'doctor_id' => $appointment->doctor_id,
            'department_id' => $appointment->department_id,
            'appointment_date' => $appointment->getRawOriginal('appointment_date'),
            'appointment_time' => $appointment->getRawOriginal('appointment_time'),
            'reason' => $appointment->reason,
            'notes' => $appointment->notes,
            'status' => $appointment->status,
        ], $validated);

        $this->ensureDoctorDepartment(
            $effectiveValues['doctor_id'],
            $effectiveValues['department_id']
        );

        if (in_array($effectiveValues['status'], ['scheduled', 'confirmed'], true)) {
            $this->ensureSlotAvailable(
                $effectiveValues['doctor_id'],
                $effectiveValues['appointment_date'],
                $effectiveValues['appointment_time'],
                $appointment->id
            );
        }

        $appointment->update($validated);

        return response()->json([
            'success' => true,
            'message' => 'Appointment updated successfully.',
            'data' => $appointment->fresh([
                'patient',
                'doctor',
                'department',
            ]),
        ]);
    }

    public function destroy(Appointment $appointment): JsonResponse
    {
        // Preserve appointment history and release its active slot.
        $appointment->update([
            'status' => 'cancelled',
        ]);

        return response()->json([
            'success' => true,
            'message' => 'Appointment cancelled successfully.',
        ]);
    }

    private function validateAppointment(
        Request $request,
        bool $isPatch = false
    ): array {
        $required = $isPatch ? 'sometimes' : 'required';

        return $request->validate([
            'patient_id' => [
                $required,
                'integer',
                'exists:patients,id',
            ],
            'doctor_id' => [
                $required,
                'integer',
                'exists:doctors,id',
            ],
            'department_id' => [
                $required,
                'integer',
                'exists:departments,id',
            ],
            'appointment_date' => [
                $required,
                'date_format:Y-m-d',
                'after_or_equal:today',
            ],
            'appointment_time' => [
                $required,
                'date_format:H:i',
            ],
            'reason' => ['sometimes', 'nullable', 'string', 'max:2000'],
            'notes' => ['sometimes', 'nullable', 'string', 'max:5000'],
            'status' => [
                'sometimes',
                'required',
                Rule::in(self::STATUSES),
            ],
        ]);
    }

    private function ensureDoctorDepartment(
        int|string $doctorId,
        int|string $departmentId
    ): void {
        $doctor = Doctor::findOrFail($doctorId);

        if ((int) $doctor->department_id !== (int) $departmentId) {
            throw ValidationException::withMessages([
                'department_id' => [
                    'The selected department does not belong to this doctor.',
                ],
            ]);
        }
    }

    private function ensureSlotAvailable(
        int|string $doctorId,
        string $date,
        string $time,
        ?int $ignoreAppointmentId = null
    ): void {
        $query = Appointment::where('doctor_id', $doctorId)
            ->whereDate('appointment_date', $date)
            ->where('appointment_time', $time)
            ->whereIn('status', ['scheduled', 'confirmed']);

        if ($ignoreAppointmentId !== null) {
            $query->where('id', '!=', $ignoreAppointmentId);
        }

        if ($query->exists()) {
            throw ValidationException::withMessages([
                'appointment_time' => [
                    'This doctor already has an active appointment at that date and time.',
                ],
            ]);
        }
    }
}
